//! Cargo-workspace integration.
//!
//! Generates the `[workspace]` region of a hybrid root `Cargo.toml` declaring
//! every Rust repo in the active project as a workspace member, then lets
//! `cargo generate-lockfile` produce a shared `Cargo.lock`.
//!
//! ## Hybrid file ownership (the cargo merge port)
//!
//! `Cargo.toml` is a **hybrid** file: rwv owns a declared key set, the user
//! owns everything else. Authoring goes through the shared `TomlDoc`
//! helper in [`crate::integrations::merge`], which preserves comments, key
//! order, profile blocks, lints, `[patch]` tables, and per-key formatting
//! byte-for-semantics across `toml_edit::DocumentMut` round-trips.
//!
//! **Owned keys** (the only bytes rwv writes):
//! - `[workspace].members`
//! - `[workspace].resolver` (always `"2"`)
//! - `[workspace.package]` (only when `workspace-package: true`)
//!
//! Everything else — `[profile.*]`, `[workspace.dependencies]`,
//! `[workspace.lints.*]`, `[workspace.metadata.*]`, `[patch.*]`, stray
//! top-level `[package]`, comments — is user policy and is **never**
//! written or stripped.
//!
//! **Marker:** the per-key TOML decoration `# managed by rwv` (a comment
//! line attached as the prefix of each owned key). Position-independent;
//! survives reordering; never injects a top-level header into a user file.
//! See [`crate::integrations::merge::TomlDoc`] for the format details.
//!
//! **Activate** = read-or-empty → merge-set the owned keys (via
//! `merge_activate`) → write. If the file is missing it is created with
//! only the managed region. The legacy `# Generated by rwv` first-line
//! header is gone.
//!
//! **Deactivate** = `strip_deactivate` — gate on the marker, strip the
//! owned keys, prune empty `[workspace]`, delete the file iff it would
//! otherwise be empty. Hand-written `Cargo.toml` files (no marker) are
//! left strictly alone — the strip is a no-op.
//!
//! ## Design decisions
//!
//! **(a) Members sub-path config.** `CargoWorkspaceConfig::members` maps a
//! repo path string to a `MemberSpec{include, exclude}`. When a repo appears
//! in this map, its root is NOT treated as a member; instead,
//! `<repo>/<inc_path>` is emitted for each `include` entry minus `exclude`.
//! Repos absent from the map keep the current root-as-member auto-behavior.
//! This is what lets rvtty (no root `Cargo.toml`, sub-packages `daemon/`,
//! `client/`, `common/`) contribute its packages to the weave workspace
//! instead of being excluded.
//!
//! **(b) Merge-preserve scope.** Owns ONLY `[workspace].members`,
//! `[workspace].resolver`, and (behind `workspace_package: true`)
//! `[workspace.package]`. All other tables are user policy and survive
//! every activate/deactivate cycle unmodified.
//!
//! **(c) Cross-repo `[patch]` — three modes (`PatchMode`).**
//!
//! - `off` (default; also accepted as `patch: false`): all-internal —
//!   operators commit relative `path = "..."` deps in member manifests;
//!   rwv never touches `[patch]`.
//! - `committed-paths` (also accepted as `patch: true`, pre-2026 behavior):
//!   `activate()` scans each member's `Cargo.toml` for cross-repo path
//!   deps (entries whose resolved path lands inside another known member
//!   dir) and writes `[patch.crates-io].<crate> = { path = "<member>" }`
//!   entries at the weave-root `Cargo.toml`.
//! - `derived`: `activate()` builds an index of every in-weave crate
//!   (member paths + reference-role repo paths) → package name, then
//!   matches each member's **registry** deps by crate name and emits
//!   `[patch.crates-io].<crate> = { path = "<in-weave>" }` entries.
//!   Git-source deps emit `[patch."<git-url>"].<crate> = ...` entries.
//!   Sovereign members declaring `beads-core = "0.3"` get the in-weave
//!   fork without committing anything weave-relative. Version-incompatible
//!   in-weave crates are skipped (with warning to stderr); a member's own
//!   `.cargo/config.toml` shadowing the same key is surfaced at generation
//!   time (cargo silently voids the weave entry).
//!
//! In both patch modes, each generated entry is decorated with the
//! `# managed by rwv` marker. User-authored `[patch.crates-io]` entries
//! are preserved (verify-and-warn at the entry level); `deactivate` strips
//! only the marked entries, then prunes the table if empty.
//!
//! **Patch surface** (orthogonal to mode; `PatchSurface` enum in the config):
//!
//! - `manifest` (default; pre-2026 behavior): entries land in the managed
//!   weave-root `Cargo.toml` under `[patch.*]`. Reaches every consumer of
//!   the workspace manifest but CANNOT reach nested-workspace opt-outs
//!   (cargo hard-errors on nested workspace members, so those repos opt
//!   out and the workspace manifest never applies to their builds).
//! - `cargo-config`: entries land in a generated `.cargo/config.toml`
//!   alongside `Cargo.toml` (project dir, symlinked to the weave root).
//!   Config-level `[patch]` is discovered upward from cwd, so nested-
//!   workspace opt-outs (rvtty, mcp_agent_mail_rust) built from *inside*
//!   the member dir see the weave's patches — the nesting-immune surface.
//!   Symlinked `.cargo/` dirs work with zero rebuild churn; relative paths
//!   resolve against the config's logical, non-canonicalized location;
//!   upward discovery traverses nested workspaces; and a member's own
//!   closest config wins per key, which the observatory scan detects.
//!
//! Both surfaces at once is structurally impossible (`PatchSurface` is an
//! enum, not two booleans). Emitting the same `[patch.<reg>].<crate>` key
//! on both would be a genuine double-patch — config-level shadows manifest-
//! level per cargo's precedence, but the strip pass would then have to
//! coordinate across two files. One surface at a time keeps the invariant
//! local.
//!
//! **Housekeeping — project-dir untracked state.** Under `cargo-config`
//! surface the project dir carries a generated `.cargo/config.toml`
//! alongside the pre-existing `Cargo.toml` and `.rwv-owned-digests`. All
//! three are treated the same way: they are part of the composition (or
//! its bookkeeping) and are committable persistent state, matching how
//! the managed `Cargo.toml` is treated. rwv does NOT auto-manage a
//! `.gitignore` for them — the operator commits them if they want the
//! composition reproducible from the repo, or gitignores them locally if
//! they prefer to regenerate on activation. This matches the existing
//! Cargo.lock / `.rwv-owned-digests` treatment: rwv publishes the file at
//! a stable location; operator policy decides what git sees.
//!
//! **(d) Nested-workspace hard error.** Refinement: a repo listed under
//! `members.<repo>` is exempt from the `declares_workspace()` check on its
//! **root** (its sub-packages, not its root, are the declared members).
//! However, if such a repo's root *does* declare `[workspace]`, that is still
//! a hard error — the ancestor-walk would bind sub-packages to it.
//!
//! ## Per-repo opt-out
//!
//! Repos can be opted out of the cargo workspace via the integration config:
//!
//! ```yaml
//! integrations:
//!   cargo-workspace:
//!     exclude:
//!       - github/cwalv/mcp_agent_mail_rust
//! ```
//!
//! Opted-out repos are dropped from `members`. (The pre-port behavior of
//! emitting `# excluded: <path> (opted out)` comments above the `[workspace]`
//! block is gone — the TomlDoc helper authors keys, not free-floating
//! comments. Operators see exclusions in `rwv.yaml`; surfacing them via
//! `check()` is a separate concern.)
//!
//! Opt-out keys that don't match any active Rust repo are silently ignored
//! (so leaving a stale entry behind after removing a repo is not an error).

