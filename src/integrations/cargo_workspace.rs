#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_simple_workspace_header() {
        let s = "[workspace]\nmembers = []\n";
        assert!(declares_workspace(s));
    }

    #[test]
    fn detects_virtual_workspace_without_package() {
        // Virtual workspace: only [workspace], no [package] section.
        let s = "[workspace]\nmembers = [\"crate-a\"]\nresolver = \"2\"\n";
        assert!(declares_workspace(s));
    }

    #[test]
    fn detects_workspace_subtable_header() {
        // Some Cargo.toml files start with `[workspace.package]` etc.
        let s = "[package]\nname = \"foo\"\n[workspace.package]\nversion = \"1\"\n";
        assert!(declares_workspace(s));
    }

    #[test]
    fn ignores_workspace_inside_comment() {
        let s = "# [workspace]\n[package]\nname = \"foo\"\n";
        assert!(!declares_workspace(s));
    }

    #[test]
    fn ignores_workspace_inside_string_value() {
        // The literal text `[workspace]` appearing in a value (not at line
        // start as a header) should not trip detection.
        let s = "[package]\nname = \"foo\"\ndescription = \"see [workspace] docs\"\n";
        assert!(!declares_workspace(s));
    }

    #[test]
    fn ignores_workspaceish_lookalike() {
        let s = "[workspaceish]\nx = 1\n";
        assert!(!declares_workspace(s));
    }

    #[test]
    fn plain_package_file_is_not_a_workspace() {
        let s = "[package]\nname = \"foo\"\nversion = \"0.1.0\"\nedition = \"2021\"\n";
        assert!(!declares_workspace(s));
    }

    #[test]
    fn member_spec_resolve_filters_excludes() {
        let spec = MemberSpec {
            include: vec!["daemon".into(), "client".into(), "common".into()],
            exclude: vec!["common".into()],
        };
        assert_eq!(resolve_member_spec(&spec), vec!["client", "daemon"]);
    }

    #[test]
    fn member_spec_resolve_empty_include_is_empty() {
        let spec = MemberSpec::default();
        assert!(resolve_member_spec(&spec).is_empty());
    }
}
