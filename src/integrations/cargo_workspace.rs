//! Cargo-workspace integration.
//!
//! Generates the `[workspace]` region of a hybrid root `Cargo.toml` declaring
//! every Rust repo in the active project as a workspace member, then lets
//! `cargo generate-lockfile` produce a shared `Cargo.lock`.
//!
//! ## Hybrid file ownership (fo-cnpjy.7 — the cargo merge port)
//!
//! `Cargo.toml` is a **hybrid** file: rwv owns a declared key set, the user
//! owns everything else. Authoring goes through the shared `TomlDoc`
//! helper in [`crate::integrations::merge`], which preserves comments, key
//! order, profile blocks, lints, `[patch]` tables, and per-key formatting
//! byte-for-semantics across `toml_edit::DocumentMut` round-trips.
//!
//! **Owned keys** (the only bytes rwv writes):
//! - `[workspace].members`
//! - `[workspace].resolver` (always `"2"`)
//! - `[workspace.package]` (only when `workspace-package: true`)
//!
//! Everything else — `[profile.*]`, `[workspace.dependencies]`,
//! `[workspace.lints.*]`, `[workspace.metadata.*]`, `[patch.*]`, stray
//! top-level `[package]`, comments — is user policy and is **never**
//! written or stripped.
//!
//! **Marker:** the per-key TOML decoration `# managed by rwv` (a comment
//! line attached as the prefix of each owned key). Position-independent;
//! survives reordering; never injects a top-level header into a user file.
//! See [`crate::integrations::merge::TomlDoc`] for the format details.
//!
//! **Activate** = read-or-empty → merge-set the owned keys (via
//! `merge_activate`) → write. If the file is missing it is created with
//! only the managed region. The legacy `# Generated by rwv` first-line
//! header is gone.
//!
//! **Deactivate** = `strip_deactivate` — gate on the marker, strip the
//! owned keys, prune empty `[workspace]`, delete the file iff it would
//! otherwise be empty. Hand-written `Cargo.toml` files (no marker) are
//! left strictly alone — the strip is a no-op.
//!
//! ## Design decisions — locked in fo-cnpjy.6 (plan §7.2)
//!
//! **(a) Members sub-path config.** `CargoWorkspaceConfig::members` maps a
//! repo path string to a `MemberSpec{include, exclude}`. When a repo appears
//! in this map, its root is NOT treated as a member; instead,
//! `<repo>/<inc_path>` is emitted for each `include` entry minus `exclude`.
//! Repos absent from the map keep the current root-as-member auto-behavior.
//! This is what lets rvtty (no root `Cargo.toml`, sub-packages `daemon/`,
//! `client/`, `common/`) contribute its packages to the weave workspace
//! instead of being excluded. See `cargo-workspace-vs-repo.md` §179–212.
//!
//! **(b) Merge-preserve scope.** Owns ONLY `[workspace].members`,
//! `[workspace].resolver`, and (behind `workspace_package: true`)
//! `[workspace.package]`. All other tables are user policy and survive
//! every activate/deactivate cycle unmodified.
//!
//! **(c) Cross-repo path deps / `[patch]` opt-in.** Default
//! (`patch: false`): all-internal — operators commit relative `path = "..."`
//! deps in member manifests; rwv never touches them. When `patch: true`,
//! `activate()` scans each member's `Cargo.toml` for cross-repo path deps
//! (entries whose resolved path lands inside another known member dir) and
//! writes `[patch.crates-io].<crate> = { path = "<member>" }` entries at the
//! weave-root `Cargo.toml`, each decorated with the `# managed by rwv`
//! marker. User-authored `[patch.crates-io]` entries are preserved
//! (verify-and-warn at the entry level); `deactivate` strips only the
//! marked entries, then prunes the table if empty.
//!
//! **(d) Nested-workspace hard error.** Refinement: a repo listed under
//! `members.<repo>` is exempt from the `declares_workspace()` check on its
//! **root** (its sub-packages, not its root, are the declared members).
//! However, if such a repo's root *does* declare `[workspace]`, that is still
//! a hard error — the ancestor-walk would bind sub-packages to it.
//!
//! ## Per-repo opt-out
//!
//! Repos can be opted out of the cargo workspace via the integration config:
//!
//! ```yaml
//! integrations:
//!   cargo-workspace:
//!     exclude:
//!       - github/cwalv/mcp_agent_mail_rust
//! ```
//!
//! Opted-out repos are dropped from `members`. (The pre-port behavior of
//! emitting `# excluded: <path> (opted out)` comments above the `[workspace]`
//! block is gone — the TomlDoc helper authors keys, not free-floating
//! comments. Operators see exclusions in `rwv.yaml`; surfacing them via
//! `check()` is a separate concern.)
//!
//! Opt-out keys that don't match any active Rust repo are silently ignored
//! (so leaving a stale entry behind after removing a repo is not an error).

use crate::integration::{Integration, IntegrationContext, Issue, Severity};
use crate::integrations::merge::{
    keypath, merge_activate, strip_deactivate, KeyPath, ManagedDoc, MergeResult, OwnedValue,
    Ownership, TomlDoc,
};
use crate::manifest::{CargoWorkspaceConfig, MemberSpec};
use anyhow::Context;
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

pub struct CargoWorkspace;

impl CargoWorkspace {
    /// Are there active cargo workspace contributions in this context?
    ///
    /// Returns `true` if at least one of:
    /// - a repo with a root `Cargo.toml` is detected (the usual case), OR
    /// - a configured `members.<repo>` entry names an active manifest repo
    ///   (the members-subpath case, e.g. rvtty — no root file but
    ///   `cfg.members.<repo>.include` contributes sub-packages).
    ///
    /// The second arm is what unblocks fo-cnpjy.8 scenario 4: without it
    /// `activate()` early-returns and the rvtty case never reaches
    /// `partition()`.
    fn has_active_cargo_work(ctx: &IntegrationContext, cfg: &CargoWorkspaceConfig) -> bool {
        if !ctx.detect_repos_with_manifest("Cargo.toml").is_empty() {
            return true;
        }
        // Any configured-members repo that is active in the manifest counts.
        ctx.active_repos()
            .any(|(rp, _)| cfg.members.contains_key(rp.as_str()))
    }

    /// Compute the sorted member-path list and the nested-workspace
    /// conflict list for the active Rust repos.
    ///
    /// Behavior:
    /// - A repo in `cfg.exclude` is dropped entirely (no member emitted, no
    ///   workspace check).
    /// - A repo listed under `cfg.members` (a `MemberSpec`) does NOT
    ///   contribute its root as a member; it contributes
    ///   `<repo>/<inc>` for each `inc` in `include` minus `exclude` instead.
    ///   Its root is exempt from the `declares_workspace()` check **unless**
    ///   the root itself actually declares `[workspace]` (still a hard error —
    ///   the ancestor-walk binds sub-packages to it).
    /// - Any other Rust repo contributes its root as a member; if the root
    ///   declares `[workspace]`, it joins the nested-conflict list.
    ///
    /// **Members-subpath repos without a root Cargo.toml** (fo-cnpjy.8): a
    /// repo listed under `cfg.members` whose root has no `Cargo.toml` (the
    /// canonical rvtty olb.5.4 shape — sub-packages `daemon/`/`client/`/...
    /// with no root manifest) is still emitted: `detect_repos_with_manifest`
    /// would miss it (its filter is "Cargo.toml at the root"), but the
    /// `members.<repo>` config is the explicit "this repo contributes sub-
    /// path packages" signal. With no root file there is no `[workspace]` to
    /// conflict with, so the nested-workspace check is moot for that path.
    ///
    /// Returns `(members, nested_conflicts)`. `members` is sorted
    /// lexicographically (the on-disk ordering the toml_edit array honors).
    fn partition(
        ctx: &IntegrationContext,
        cfg: &CargoWorkspaceConfig,
    ) -> anyhow::Result<(Vec<String>, Vec<String>)> {
        let rust_repos = ctx.detect_repos_with_manifest("Cargo.toml");
        let rust_repo_set: BTreeSet<&str> = rust_repos.iter().map(String::as_str).collect();
        let opt_out: BTreeSet<&str> = cfg.exclude.iter().map(String::as_str).collect();

        // Build the iteration set: union of (a) repos with a root Cargo.toml
        // and (b) configured-member repos that are active in the manifest.
        // The second set is what unblocks the rvtty case — a repo whose
        // sub-packages are the members has no root file, so detect_repos_*
        // misses it; the explicit cfg.members entry provides the signal.
        let active_members_in_cfg: BTreeSet<String> = ctx
            .active_repos()
            .map(|(rp, _)| rp.as_str().to_string())
            .filter(|p| cfg.members.contains_key(p))
            .collect();

        let mut all_repos: BTreeSet<String> = BTreeSet::new();
        all_repos.extend(rust_repos.iter().cloned());
        all_repos.extend(active_members_in_cfg.iter().cloned());

        let mut members: Vec<String> = Vec::new();
        let mut nested_conflicts: Vec<String> = Vec::new();

        for repo in &all_repos {
            if opt_out.contains(repo.as_str()) {
                continue;
            }

            // Only read the root Cargo.toml if it actually exists. A
            // members-subpath repo (no root Cargo.toml) skips this — the
            // nested-workspace check is moot when there is no root manifest
            // to declare `[workspace]`.
            let root_has_workspace = if rust_repo_set.contains(repo.as_str()) {
                let cargo_toml = ctx.workspace_root.join(repo).join("Cargo.toml");
                let content = std::fs::read_to_string(&cargo_toml)
                    .with_context(|| format!("failed to read {}", cargo_toml.display()))?;
                declares_workspace(&content)
            } else {
                false
            };

            if let Some(spec) = cfg.members.get(repo) {
                // members.<repo> sub-path mode.
                // Refinement (plan §7.2-d): if the repo root itself declares
                // [workspace] this is STILL a hard error — sub-packages can't
                // dodge an ancestor workspace declaration via member
                // configuration.
                if root_has_workspace {
                    nested_conflicts.push(repo.clone());
                    continue;
                }
                for sub in resolve_member_spec(spec) {
                    members.push(format!("{repo}/{sub}"));
                }
            } else if root_has_workspace {
                nested_conflicts.push(repo.clone());
            } else {
                members.push(repo.clone());
            }
        }

        members.sort();
        members.dedup();
        Ok((members, nested_conflicts))
    }

    /// Build the (key, ownership, value) triples the merge helper will set
    /// during `activate()`. Pure — no I/O.
    fn owned_pairs(
        members: &[String],
        cfg: &CargoWorkspaceConfig,
    ) -> Vec<(KeyPath, Ownership, OwnedValue)> {
        let mut owned: Vec<(KeyPath, Ownership, OwnedValue)> = Vec::with_capacity(3);

        owned.push((
            keypath(["workspace", "members"]),
            Ownership::Author,
            OwnedValue::Array(members.to_vec()),
        ));
        owned.push((
            keypath(["workspace", "resolver"]),
            Ownership::Author,
            OwnedValue::String("2".to_string()),
        ));

        if cfg.workspace_package {
            // The cargo-workspace-vs-repo.md design surfaces `rwv.yaml`
            // `project.{license, authors, description, repository, ...}` into
            // `[workspace.package]`. The Manifest type does not yet carry a
            // `project` section (cargo-workspace-vs-repo.md §324-376 is the
            // forward-looking design; the manifest extension is a separate
            // bead). Until that lands, the opt-in writes an empty
            // `[workspace.package]` table.
            //
            // The wiring is correct: when the project metadata field lands,
            // populate the BTreeMap below from it; the TomlDoc merge-into-
            // existing-table behavior will set each sub-key while preserving
            // user-added ones.
            owned.push((
                keypath(["workspace", "package"]),
                Ownership::Author,
                OwnedValue::Object(std::collections::BTreeMap::new()),
            ));
        }

        owned
    }
}

impl Integration for CargoWorkspace {
    fn name(&self) -> &str {
        "cargo-workspace"
    }

    fn default_enabled(&self) -> bool {
        true
    }

    fn activate(&self, ctx: &IntegrationContext) -> anyhow::Result<()> {
        let cfg: CargoWorkspaceConfig = ctx.config.settings()?;

        // Early-return when there are no rust repos AND no configured members.
        // A members-subpath repo (e.g. rvtty: no root Cargo.toml) is invisible
        // to detect_repos_with_manifest but is the explicit signal that this
        // repo contributes sub-package members; we must still proceed.
        if !Self::has_active_cargo_work(ctx, &cfg) {
            return Ok(());
        }

        let (members, nested_conflicts) = Self::partition(ctx, &cfg)?;

        if !nested_conflicts.is_empty() {
            anyhow::bail!("{}", nested_workspace_error(&nested_conflicts));
        }

        // `output_dir = project_dir` (plan §4.1) — the committed `Cargo.toml`
        // lives in the project directory and the weave-root symlink surfaces
        // it. Writing through `output_dir` writes into the committed file.
        let path = ctx.output_dir.join("Cargo.toml");
        let owned = Self::owned_pairs(&members, &cfg);

        let _result: MergeResult = merge_activate::<TomlDoc>(&path, &owned)
            .with_context(|| format!("merge-activate {}", path.display()))?;

        // When `cfg.patch == true`, opt the weave into rwv-generated `[patch]`
        // entries for cross-repo path deps (plan §5a-c). Patch entries are
        // dynamic (one per cross-repo path dep), not a fixed owned-key set,
        // so they don't fit `merge_activate`'s static `(KeyPath, OwnedValue)`
        // contract; we write them post-merge using toml_edit directly.
        //
        // Each entry is an inline table `<crate> = { path = "<rel>" }` under
        // `[patch.crates-io]`, decorated with the `# managed by rwv` marker
        // on the leaf key so the strip-deactivate pass can discriminate
        // rwv-authored entries from user-authored ones.
        if cfg.patch {
            let patches = Self::compute_patches(ctx, &members)
                .context("computing cross-repo path-dep patches")?;
            if !patches.is_empty() {
                Self::merge_patch_entries(&path, &patches)
                    .with_context(|| format!("merge-patch {}", path.display()))?;
            }
        }

        // `MergeResult.deferred` lists keys the user took the pen on (a
        // hand-written `[workspace]` block with no marker). The trigger-model
        // story is that context verbs verify-and-warn rather than author;
        // surfacing deferrals as `Severity::Warning` is a framework concern
        // tracked by C3 (`generated_files()` split + verify split). For now
        // the merge silently defers — consistent with the pre-port behavior
        // of leaving hand-written files alone.

        Ok(())
    }

    fn deactivate(&self, root: &Path) -> anyhow::Result<()> {
        // `root` is the project_dir per the framework's deactivate contract
        // (`integration_runner::run_deactivations`). It is the same path
        // `output_dir` resolved to during activate.
        let path = root.join("Cargo.toml");
        let owned_keys = Self::deactivate_owned_keys();
        strip_deactivate::<TomlDoc>(&path, &owned_keys)
            .with_context(|| format!("strip-deactivate {}", path.display()))?;

        // Second pass: strip rwv-marker-decorated `[patch.crates-io].*`
        // entries. This is independent of the workspace marker — patch
        // entries carry their own per-key marker decor, so they may need
        // stripping even when `strip_deactivate` left the file unchanged
        // (e.g. the user holds the pen on `[workspace]`). The generic
        // strip_deactivate has no static handle on the dynamic
        // patch.crates-io.<name> key set, so this is handled here.
        Self::strip_marked_patch_entries(&path)
            .with_context(|| format!("strip-patch {}", path.display()))?;

        Ok(())
    }

    fn check(&self, ctx: &IntegrationContext) -> anyhow::Result<Vec<Issue>> {
        let cfg: CargoWorkspaceConfig = ctx.config.settings()?;
        if !Self::has_active_cargo_work(ctx, &cfg) {
            return Ok(vec![]);
        }

        let mut issues = Vec::new();
        if which::which("cargo").is_err() {
            issues.push(Issue {
                integration: self.name().to_string(),
                severity: Severity::Warning,
                message: "cargo is not on PATH".to_string(),
                safe_to_fix: true,
            });
        }

        // Surface nested-workspace conflicts as errors during `rwv doctor`
        // so operators see the same diagnostic without having to run lock.
        let (_, nested_conflicts) = Self::partition(ctx, &cfg)?;
        if !nested_conflicts.is_empty() {
            issues.push(Issue {
                integration: self.name().to_string(),
                severity: Severity::Error,
                message: nested_workspace_error(&nested_conflicts),
                safe_to_fix: true,
            });
        }

        Ok(issues)
    }

    fn activate_hook(&self, ctx: &IntegrationContext) -> anyhow::Result<()> {
        let cfg: CargoWorkspaceConfig = ctx.config.settings()?;
        if !Self::has_active_cargo_work(ctx, &cfg) {
            return Ok(());
        }

        // Run from workspace_root: that's where activation symlinks are
        // in place so cargo sees the workspace the user sees. output_dir
        // (project_dir) is where the canonical Cargo.toml lives, but the
        // member paths in it are resolved relative to the symlink at
        // workspace_root.
        let status = std::process::Command::new("cargo")
            .arg("generate-lockfile")
            .current_dir(ctx.workspace_root)
            .status()
            .context("failed to run cargo")?;

        if !status.success() {
            anyhow::bail!("cargo generate-lockfile failed (exit {})", status);
        }

        Ok(())
    }

    /// `Cargo.lock` is fully-owned — gitignore-eligible, whole-deletable.
    fn generated_files(&self, ctx: &IntegrationContext) -> Vec<String> {
        let Ok(cfg) = ctx.config.settings::<CargoWorkspaceConfig>() else {
            return vec![];
        };
        if !Self::has_active_cargo_work(ctx, &cfg) {
            return vec![];
        }
        vec!["Cargo.lock".to_string()]
    }

    /// Verify that the on-disk `Cargo.toml` reflects the current intent
    /// (`rwv.yaml` membership configuration). Called by `rwv doctor` and
    /// context verbs; **read-only** — never authors content.
    ///
    /// Three findings (see bead fo-cnpjy.18 design doc for rationale):
    ///
    /// - **MISSING** (`safe_to_fix = true`): file absent; `--fix` regenerates.
    /// - **DRIFT** (`safe_to_fix = true`): markers present but on-disk values
    ///   of owned keys differ from config; `--fix` regenerates.
    /// - **USER-HELD** (`safe_to_fix = false`): file present with
    ///   `[workspace]` members/resolver but **no** `# managed by rwv` marker
    ///   on the owned keys — the user holds the pen. Doctor surfaces the
    ///   finding but never auto-overwrites.
    ///
    /// CLEAN (no issues) when markers present AND values match config.
    fn verify(&self, ctx: &IntegrationContext) -> anyhow::Result<Vec<Issue>> {
        let cfg: CargoWorkspaceConfig = ctx.config.settings()?;

        if !Self::has_active_cargo_work(ctx, &cfg) {
            return Ok(vec![]);
        }

        let path = ctx.output_dir.join("Cargo.toml");

        // ── MISSING ────────────────────────────────────────────────────────
        if !path.exists() {
            return Ok(vec![Issue {
                integration: self.name().to_string(),
                severity: Severity::Warning,
                message: format!(
                    "cargo-workspace managed file missing: {}; run rwv doctor --fix to regenerate",
                    path.display()
                ),
                safe_to_fix: true,
            }]);
        }

        // Parse the on-disk file. A parse failure is surfaced as an error
        // (can't assess drift on a malformed file, and auto-repair of a
        // malformed file is potentially data-lossy).
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {} for verify", path.display()))?;
        let toml_doc = TomlDoc::parse(&text)
            .with_context(|| format!("parsing {} for verify", path.display()))?;
        // Also parse as toml_edit::DocumentMut for reading values.
        let edit_doc: toml_edit::DocumentMut = text
            .parse()
            .with_context(|| format!("parsing {} for verify (toml_edit)", path.display()))?;

        // Build the owned key set (same as activate uses).
        let owned_keys: Vec<KeyPath> = vec![
            keypath(["workspace", "members"]),
            keypath(["workspace", "resolver"]),
        ];

        let marker_present = toml_doc.has_marker(&owned_keys);

        // ── USER-HELD ──────────────────────────────────────────────────────
        // File has [workspace] with members/resolver but no rwv marker.
        if !marker_present
            && (toml_doc.key_present(&keypath(["workspace", "members"]))
                || toml_doc.key_present(&keypath(["workspace", "resolver"])))
        {
            return Ok(vec![Issue {
                integration: self.name().to_string(),
                severity: Severity::Warning,
                message: format!(
                    "cargo-workspace managed file present but unmarked: {}; \
                     rwv will NOT auto-take-over (would discard user content). \
                     Cut over manually by removing [workspace] from the file \
                     or by exercising the intent-mode merge",
                    path.display()
                ),
                safe_to_fix: false,
            }]);
        }

        // ── DRIFT ──────────────────────────────────────────────────────────
        // Markers are present (or the file has no [workspace] at all and
        // `merge_activate` would create one). Compare on-disk owned values
        // against what the current config would produce.
        //
        // Only `Ownership::Author` keys are checked for drift. Keys with
        // `Ownership::DefaultOnly` ownership are intentionally user-adjustable
        // after rwv writes the initial default value; any difference between
        // the on-disk value and rwv's default is CLEAN, not DRIFT. Currently
        // all cargo-workspace owned keys are `Ownership::Author`, so this
        // policy has no observable effect here yet — it is documented for
        // future keys that might use `Ownership::DefaultOnly`.
        //
        // Skip the nested-conflict check here — `check()` already surfaces
        // that as an Error; we don't duplicate it in verify().
        let (members, nested_conflicts) = Self::partition(ctx, &cfg)?;
        if !nested_conflicts.is_empty() {
            // Nested-workspace conflict: activation would fail anyway;
            // don't add a misleading DRIFT finding on top of the check error.
            return Ok(vec![]);
        }

        // Read on-disk members and resolver from the toml_edit document.
        let on_disk_members = toml_array_strings(&edit_doc, &["workspace", "members"]);
        let on_disk_resolver = toml_string(&edit_doc, &["workspace", "resolver"]);

        let expected_resolver = "2".to_string();

        // Both `members` and `resolver` are Ownership::Author keys — drift is
        // a DRIFT finding (safe_to_fix = true).
        let members_drift = on_disk_members.as_deref() != Some(members.as_slice());
        let resolver_drift = on_disk_resolver.as_deref() != Some(expected_resolver.as_str());

        if members_drift || resolver_drift {
            return Ok(vec![Issue {
                integration: self.name().to_string(),
                severity: Severity::Warning,
                message: format!(
                    "cargo-workspace managed file has drift: {}; \
                     on-disk [workspace] content differs from rwv.yaml config. \
                     Run rwv doctor --fix to regenerate",
                    path.display()
                ),
                safe_to_fix: true,
            }]);
        }

        // ── CLEAN ──────────────────────────────────────────────────────────
        Ok(vec![])
    }

    /// `Cargo.toml` is **hybrid** (rwv owns the `[workspace]` region; the
    /// user owns `[profile.*]`, `[workspace.lints.*]`, `[workspace.dependencies]`,
    /// `[patch.*]`, comments, etc.). It MUST NOT appear in
    /// `generated_files()` — that would mark it gitignore-eligible and
    /// whole-deletable, the exact data-loss bug the merge port fixes.
    fn managed_files(&self, ctx: &IntegrationContext) -> Vec<String> {
        let mut files = self.generated_files(ctx);
        let Ok(cfg) = ctx.config.settings::<CargoWorkspaceConfig>() else {
            return files;
        };
        if Self::has_active_cargo_work(ctx, &cfg) {
            files.push("Cargo.toml".to_string());
        }
        files
    }
}

impl CargoWorkspace {
    /// The owned key paths stripped on `deactivate(root)`. Static because
    /// `Integration::deactivate` has no `IntegrationContext` — see
    /// `integration.rs:154`. Plan §3 / §11 res #15:
    ///
    /// - `members` and `resolver` are stripped unconditionally — they are
    ///   the always-owned keys.
    /// - `workspace.package` is also stripped unconditionally. The marker
    ///   gate in `strip_deactivate` is per-key: if the key was never
    ///   authored (the opt-in was off), no decor exists, and the strip is a
    ///   no-op for that key. If it WAS authored, stripping is correct.
    ///   This avoids leaking the activate-time `workspace_package` boolean
    ///   into the deactivate path (which doesn't have the config).
    fn deactivate_owned_keys() -> Vec<KeyPath> {
        vec![
            keypath(["workspace", "members"]),
            keypath(["workspace", "resolver"]),
            keypath(["workspace", "package"]),
        ]
    }

    /// Compute the `[patch.crates-io]` entries rwv should generate, when
    /// `cfg.patch == true`.
    ///
    /// Approach (plan §5a-c, opt-in `[patch]` for publishable crates):
    ///
    /// 1. Build an index of every member: `member_path -> crate_name` by
    ///    reading each `<member>/Cargo.toml`'s `[package].name`.
    /// 2. Scan each member's `[dependencies]` and `[dev-dependencies]` for
    ///    entries that include `path = "<rel>"`.
    /// 3. Resolve `<rel>` against the member's directory. If the resolved
    ///    target equals another member's directory, emit a patch entry
    ///    keyed by that other member's crate name, with `path = "<member>"`
    ///    (weave-root-relative).
    ///
    /// This is "the cheapest approach that works for the rvtty case": we
    /// only scan the member manifests, not all repo Cargo.tomls, and we
    /// don't peek at `rwv.lock`'s topology. Cross-repo path deps not
    /// pointing at a known member are ignored (they're either intra-repo
    /// internal-only deps, or operator-managed vendor deps — neither needs
    /// a `[patch]` entry).
    ///
    /// Output is sorted by crate name (stable across runs).
    fn compute_patches(
        ctx: &IntegrationContext,
        members: &[String],
    ) -> anyhow::Result<Vec<(String, String)>> {
        // Index members by their canonicalized absolute on-disk path so we can
        // match the resolved target of a `path = "..."` dep against them. The
        // value side stores both the weave-root-relative member path (for the
        // emitted `path = "<rel>"`) and the crate name (the patch table key).
        let mut by_abs: BTreeMap<std::path::PathBuf, (String, String)> = BTreeMap::new();
        for member in members {
            let member_dir = ctx.workspace_root.join(member);
            let cargo_toml = member_dir.join("Cargo.toml");
            if !cargo_toml.exists() {
                continue;
            }
            let text = std::fs::read_to_string(&cargo_toml)
                .with_context(|| format!("reading {}", cargo_toml.display()))?;
            let doc: toml_edit::DocumentMut = text
                .parse()
                .with_context(|| format!("parsing {}", cargo_toml.display()))?;
            let Some(name) = doc
                .get("package")
                .and_then(|i| i.as_table())
                .and_then(|t| t.get("name"))
                .and_then(|i| i.as_str())
            else {
                continue;
            };
            // Best-effort canonicalize; fall back to the joined path so tests
            // that don't `canonicalize()` test dirs still work.
            let abs = std::fs::canonicalize(&member_dir).unwrap_or(member_dir.clone());
            by_abs.insert(abs, (member.clone(), name.to_string()));
        }

        let mut patches: BTreeMap<String, String> = BTreeMap::new();
        for member in members {
            let member_dir = ctx.workspace_root.join(member);
            let cargo_toml = member_dir.join("Cargo.toml");
            if !cargo_toml.exists() {
                continue;
            }
            let text = std::fs::read_to_string(&cargo_toml)
                .with_context(|| format!("reading {}", cargo_toml.display()))?;
            let doc: toml_edit::DocumentMut = text
                .parse()
                .with_context(|| format!("parsing {}", cargo_toml.display()))?;

            for deps_key in ["dependencies", "dev-dependencies"] {
                let Some(deps) = doc.get(deps_key).and_then(|i| i.as_table()) else {
                    continue;
                };
                for (_dep_name, dep_item) in deps.iter() {
                    // Path deps come in two forms:
                    //   foo = { path = "../foo" }       (inline table)
                    //   [dependencies.foo] path = "..." (sub-table)
                    let path_str = if let Some(inline) = dep_item.as_inline_table() {
                        inline.get("path").and_then(|v| v.as_str())
                    } else if let Some(table) = dep_item.as_table() {
                        table.get("path").and_then(|i| i.as_str())
                    } else {
                        None
                    };
                    let Some(rel) = path_str else { continue };

                    let target = member_dir.join(rel);
                    let target_abs = std::fs::canonicalize(&target).unwrap_or(target.clone());

                    let Some((target_member, target_crate)) = by_abs.get(&target_abs) else {
                        continue;
                    };
                    // Don't emit a patch entry for self (intra-member dep —
                    // not a workspace-cross dep).
                    if target_member == member {
                        continue;
                    }
                    patches.insert(target_crate.clone(), target_member.clone());
                }
            }
        }

        Ok(patches.into_iter().collect())
    }

    /// Merge rwv-generated `[patch.crates-io].<crate>` entries into `path`
    /// (the weave-root `Cargo.toml`). Co-requisite of `strip_marked_patch_entries`.
    ///
    /// Each entry is written as an inline table
    /// `<crate> = { path = "<rel>" }` with the `# managed by rwv` decor on the
    /// leaf key — that decor is the per-entry marker the strip pass keys off
    /// to discriminate rwv-authored entries from user-authored ones.
    ///
    /// Verify-and-warn semantics (matching the merge model): if a key is
    /// already present on disk and is NOT carrying the rwv marker, the user
    /// holds the pen — rwv leaves that entry alone.
    fn merge_patch_entries(path: &Path, patches: &[(String, String)]) -> anyhow::Result<()> {
        use crate::integrations::merge::TOML_MARKER_TEXT;

        let text = if path.exists() {
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?
        } else {
            String::new()
        };
        let mut doc: toml_edit::DocumentMut = text
            .parse()
            .with_context(|| format!("parsing {}", path.display()))?;

        // Get-or-create `[patch.crates-io]`.
        let patch = doc.as_table_mut().entry("patch").or_insert_with(|| {
            let mut t = toml_edit::Table::new();
            t.set_implicit(true);
            toml_edit::Item::Table(t)
        });
        let patch_table = match patch {
            toml_edit::Item::Table(t) => t,
            _ => anyhow::bail!("`patch` is present but is not a table"),
        };
        let crates_io = patch_table
            .entry("crates-io")
            .or_insert_with(|| toml_edit::Item::Table(toml_edit::Table::new()));
        let crates_io_table = match crates_io {
            toml_edit::Item::Table(t) => t,
            _ => anyhow::bail!("`patch.crates-io` is present but is not a table"),
        };

        for (crate_name, target_relpath) in patches {
            // Verify-and-warn: if the user already authored this entry (no
            // rwv marker on the leaf), do not overwrite.
            let user_holds_pen = crates_io_table
                .key(crate_name.as_str())
                .map(|k| {
                    let prefix = k
                        .leaf_decor()
                        .prefix()
                        .and_then(|r| r.as_str())
                        .unwrap_or("");
                    !prefix.contains(TOML_MARKER_TEXT)
                })
                .unwrap_or(false)
                && crates_io_table.contains_key(crate_name.as_str());
            if user_holds_pen {
                continue;
            }

            // Compose `{ path = "<rel>" }` inline table.
            let mut inline = toml_edit::InlineTable::new();
            inline.insert(
                "path",
                toml_edit::Value::String(toml_edit::Formatted::new(target_relpath.clone())),
            );
            crates_io_table.insert(
                crate_name.as_str(),
                toml_edit::Item::Value(toml_edit::Value::InlineTable(inline)),
            );

            // Attach the `# managed by rwv` marker on the leaf key,
            // idempotently and preserving any existing user decor lines.
            if let Some(mut key_mut) = crates_io_table.key_mut(crate_name.as_str()) {
                let decor = key_mut.leaf_decor_mut();
                let existing = decor.prefix().and_then(|r| r.as_str()).unwrap_or("");
                if !existing.contains(TOML_MARKER_TEXT) {
                    let new = if existing.is_empty() {
                        "# managed by rwv\n".to_string()
                    } else if existing.ends_with('\n') {
                        format!("{existing}# managed by rwv\n")
                    } else {
                        format!("{existing}\n# managed by rwv\n")
                    };
                    decor.set_prefix(new);
                }
            }
        }

        std::fs::write(path, doc.to_string())
            .with_context(|| format!("writing {}", path.display()))?;
        Ok(())
    }

    /// Strip every rwv-marker-decorated entry under `[patch.crates-io]`,
    /// then prune empty `[patch.crates-io]` and `[patch]` tables.
    ///
    /// Co-requisite of the activate-time `[patch.crates-io]` generation: the
    /// generic `strip_deactivate` only handles a static set of owned keys;
    /// patch entries are dynamic (one per cross-repo path dep), so they're
    /// enumerated here. The marker decor on each key is the discriminator —
    /// user-authored `[patch.crates-io].some-crate` entries (decorated by the
    /// user, not by rwv) survive.
    fn strip_marked_patch_entries(path: &Path) -> anyhow::Result<()> {
        use crate::integrations::merge::TOML_MARKER_TEXT;

        if !path.exists() {
            return Ok(());
        }
        let text =
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        let mut doc: toml_edit::DocumentMut = text
            .parse()
            .with_context(|| format!("parsing {}", path.display()))?;

        let mut changed = false;
        // Collect entries to remove under [patch.crates-io] whose key decor
        // carries the rwv marker. (We avoid mutating while iterating.)
        let to_remove: Vec<String> = doc
            .get("patch")
            .and_then(|i| i.as_table())
            .and_then(|t| t.get("crates-io"))
            .and_then(|i| i.as_table())
            .map(|t| {
                t.iter()
                    .filter_map(|(name, _)| {
                        let key = t.key(name)?;
                        let prefix = key.leaf_decor().prefix().and_then(|r| r.as_str())?;
                        if prefix.contains(TOML_MARKER_TEXT) {
                            Some(name.to_string())
                        } else {
                            None
                        }
                    })
                    .collect()
            })
            .unwrap_or_default();

        if !to_remove.is_empty() {
            if let Some(crates_io) = doc
                .get_mut("patch")
                .and_then(|i| i.as_table_mut())
                .and_then(|t| t.get_mut("crates-io"))
                .and_then(|i| i.as_table_mut())
            {
                for name in &to_remove {
                    crates_io.remove(name);
                }
                changed = true;
            }
        }

        // Prune `[patch.crates-io]` if it's now empty.
        let prune_crates_io = doc
            .get("patch")
            .and_then(|i| i.as_table())
            .and_then(|t| t.get("crates-io"))
            .and_then(|i| i.as_table())
            .is_some_and(|t| t.is_empty());
        if prune_crates_io {
            if let Some(patch) = doc.get_mut("patch").and_then(|i| i.as_table_mut()) {
                patch.remove("crates-io");
                changed = true;
            }
        }
        // Prune `[patch]` if it's now empty.
        let prune_patch = doc
            .get("patch")
            .and_then(|i| i.as_table())
            .is_some_and(|t| t.is_empty());
        if prune_patch {
            doc.as_table_mut().remove("patch");
            changed = true;
        }

        if changed {
            std::fs::write(path, doc.to_string())
                .with_context(|| format!("writing {}", path.display()))?;
        }
        Ok(())
    }
}

/// Resolve a `MemberSpec` to its effective sorted sub-path list.
///
/// `include` minus `exclude`. An empty `include` yields the empty list (no
/// members from that repo — see `MemberSpec` docs for the rationale).
/// Exclude entries that don't match any include are silently ignored.
fn resolve_member_spec(spec: &MemberSpec) -> Vec<String> {
    let exclude: BTreeSet<&str> = spec.exclude.iter().map(String::as_str).collect();
    let mut out: Vec<String> = spec
        .include
        .iter()
        .filter(|s| !exclude.contains(s.as_str()))
        .cloned()
        .collect();
    out.sort();
    out.dedup();
    out
}

/// Returns true if `content` declares a `[workspace]` section (including
/// virtual workspaces, with or without a `[package]` section, and the
/// `[workspace.<key>]` sub-table form).
///
/// Scans line-by-line for a TOML table header at line start. TOML requires
/// headers to be the first non-whitespace token on a line, so this stays
/// correct even when the file embeds the literal text `[workspace]` inside
/// a string value or a comment.
fn declares_workspace(content: &str) -> bool {
    for raw in content.lines() {
        let line = raw.trim_start();
        if line.starts_with('#') {
            continue;
        }
        // Accept both `[workspace]` and `[workspace.foo]` table headers.
        // Require a delimiter (`]` or `.`) right after `workspace` so we
        // don't match a hypothetical `[workspaceish]`.
        let after_bracket = match line.strip_prefix('[') {
            Some(rest) => rest,
            None => continue,
        };
        let after_keyword = match after_bracket.strip_prefix("workspace") {
            Some(rest) => rest,
            None => continue,
        };
        if after_keyword.starts_with(']') || after_keyword.starts_with('.') {
            return true;
        }
    }
    false
}

/// Build the actionable error message for one or more nested-workspace
/// conflicts. Pluralized so the wording reads naturally either way.
fn nested_workspace_error(conflicts: &[String]) -> String {
    let mut msg = String::new();
    if conflicts.len() == 1 {
        msg.push_str(&format!(
            "repo `{}` declares its own [workspace]; cannot be a member of \
             the cargo workspace.\n",
            conflicts[0]
        ));
    } else {
        msg.push_str(
            "the following repos declare their own [workspace] and cannot \
             be members of the cargo workspace:\n",
        );
        for repo in conflicts {
            msg.push_str(&format!("  - {}\n", repo));
        }
    }
    msg.push_str("\nresolve by one of:\n");
    msg.push_str("  - remove the nested [workspace] from the repo's Cargo.toml\n");
    msg.push_str("  - disable the cargo-workspace integration entirely in rwv.yaml\n");
    msg.push_str(
        "  - opt this repo out (per-repo) by adding its path to\n    \
         integrations.cargo-workspace.exclude in rwv.yaml\n",
    );
    msg.push_str(
        "  - for repos with sub-package layouts (no root [workspace] but\n    \
         multiple sub-crates), use integrations.cargo-workspace.members.<repo>\n    \
         with an `include:` list to contribute the sub-paths instead\n",
    );
    msg
}

