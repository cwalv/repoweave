//! `rwv workweave create` runs the install hooks in the new seat, and over a
//! `Cargo.lock` that matches its manifests the cargo hook leaves the seat's
//! project repo clean: no tracked dirt that would make the seat's `rwv
//! sync-to` refuse, whether the project commits its lock and generation
//! record or ignores them and the create carries them.
//!
//! Only a lock that does not match its manifests is rewritten — `cargo
//! fetch` prunes an entry no member needs — and that arm is the control: it
//! shows the status read sees the hook's write when there is one.
//!
//! Real `cargo`, behind a wrapper that records each run: whether a hook
//! rewrites a lock it honors is the tool's own behavior, which a stand-in
//! would only restate, and a clean seat proves nothing unless the hook ran.
//! Unix only, for the wrapper: a shebang script resolved off `PATH`.

#![cfg(unix)]

use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

mod common;

const UNUSED_ENTRY: &str = "\n[[package]]\nname = \"needed-by-no-member\"\nversion = \"0.0.1\"\n";

fn git_init_with_commit(dir: &Path) {
    common::git_in(dir, &["init", "--initial-branch=main"]);
    common::git_in(dir, &["config", "user.email", "test@test.com"]);
    common::git_in(dir, &["config", "user.name", "Test"]);
    common::git_in(dir, &["add", "-A"]);
    common::git_in(dir, &["commit", "-m", "init"]);
}

struct Weave {
    tmp: tempfile::TempDir,
    ws: PathBuf,
    path: std::ffi::OsString,
    witness: PathBuf,
}

impl Weave {
    /// A weave whose project `app` lists one dependency-free crate, its
    /// managed files authored and its lock generated by the hook, and
    /// everything the project does not ignore committed. `ignore` is the
    /// project's `.gitignore`.
    fn new(ignore: &str) -> Self {
        let tmp = common::tempdir().unwrap();
        let root = tmp.path();
        let src = root.join("lib-src");
        std::fs::create_dir_all(src.join("src")).unwrap();
        std::fs::write(
            src.join("Cargo.toml"),
            "[package]\nname = \"lib\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        )
        .unwrap();
        std::fs::write(src.join("src/lib.rs"), "").unwrap();
        git_init_with_commit(&src);
        let bare = root.join("lib.git");
        common::git_in(
            root,
            &[
                "clone",
                "--bare",
                &src.to_string_lossy(),
                &bare.to_string_lossy(),
            ],
        );
        let url = common::file_url(&bare);

        let ws = root.join("ws");
        std::fs::create_dir_all(ws.join("projects/app")).unwrap();
        common::git_in(
            root,
            &["clone", &url, &ws.join("github/acme/lib").to_string_lossy()],
        );
        let project = ws.join("projects/app");
        std::fs::write(
            project.join("rwv.toml"),
            format!(
                "[repositories.\"github/acme/lib\"]\ntype = \"git\"\nurl = \"{url}\"\n\
                 version = \"main\"\nrole = \"owned\"\n\n\
                 [integrations.vscode-workspace]\nenabled = false\n"
            ),
        )
        .unwrap();
        std::fs::write(project.join(".gitignore"), ignore).unwrap();
        git_init_with_commit(&project);
        std::fs::write(ws.join(".rwv-active"), "app\n").unwrap();

        let bin = root.join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        let witness = root.join("cargo-ran");
        let wrapper = bin.join("cargo");
        std::fs::write(
            &wrapper,
            format!(
                "#!/bin/sh\necho \"$PWD $*\" >> {}\nexec {} \"$@\"\n",
                witness.display(),
                which::which("cargo").unwrap().display()
            ),
        )
        .unwrap();
        std::fs::set_permissions(&wrapper, std::fs::Permissions::from_mode(0o755)).unwrap();
        let mut path = bin.into_os_string();
        path.push(":");
        path.push(std::env::var_os("PATH").unwrap_or_default());

        let weave = Weave {
            tmp,
            ws,
            path,
            witness,
        };
        weave.rwv(&["doctor", "--fix"]);
        assert!(
            project.join("Cargo.lock").is_file(),
            "fixture: the hook should have generated the lock"
        );
        weave.rwv(&["lock"]);
        weave.commit("authored");
        weave
    }

    fn project(&self) -> PathBuf {
        self.ws.join("projects/app")
    }

    fn seat_project(&self) -> PathBuf {
        self.tmp.path().join(".workweaves/app--seat/projects/app")
    }

    fn rwv(&self, args: &[&str]) -> String {
        let out = common::rwv()
            .args(args)
            .current_dir(&self.ws)
            .env("PATH", &self.path)
            .output()
            .expect("rwv should run");
        let report = format!(
            "{}\n{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
        assert!(
            out.status.success(),
            "`rwv {}` failed:\n{report}",
            args.join(" ")
        );
        report
    }

    fn commit(&self, message: &str) {
        common::git_in(&self.project(), &["add", "-A"]);
        common::git_in(&self.project(), &["commit", "-q", "-m", message]);
        assert_eq!(
            common::git_in(&self.project(), &["status", "--porcelain"]),
            "",
            "fixture: the source is clean before create"
        );
    }

    /// Create the seat and return its project repo's `git status`, after
    /// asserting the cargo hook ran in the seat and the source stayed clean.
    fn create(&self) -> (String, String) {
        let _ = std::fs::remove_file(&self.witness);
        let report = self.rwv(&["workweave", "app", "create", "seat"]);
        let seat = self.tmp.path().join(".workweaves/app--seat");
        let ran_in_seat = std::fs::read_to_string(&self.witness)
            .unwrap_or_default()
            .lines()
            .any(|line| {
                line.split_once(' ').is_some_and(|(cwd, args)| {
                    Path::new(cwd).canonicalize().ok() == seat.canonicalize().ok()
                        && args.starts_with("fetch")
                })
            });
        assert!(
            ran_in_seat,
            "fixture: the cargo hook must have run `cargo fetch` in the seat, or a \
             clean seat proves nothing:\n{report}"
        );
        assert!(
            self.seat_project().join("Cargo.lock").is_file(),
            "the seat holds the lock:\n{report}"
        );
        assert_eq!(
            common::git_in(&self.project(), &["status", "--porcelain"]),
            "",
            "create must leave the source clean:\n{report}"
        );
        (
            common::git_in(&self.seat_project(), &["status", "--porcelain"]),
            report,
        )
    }
}

#[test]
fn create_over_a_committed_consistent_lock_leaves_the_seat_clean() {
    if common::skip_without_tool("cargo") {
        return;
    }
    let weave = Weave::new("");
    assert!(
        !common::git_in(&weave.project(), &["ls-files", "Cargo.lock"]).is_empty(),
        "fixture: this arm commits the lock"
    );
    let (status, report) = weave.create();
    assert_eq!(
        status, "",
        "the hooks create ran must leave the seat's project repo clean:\n{report}"
    );
}

#[test]
fn create_over_a_carried_consistent_lock_leaves_the_seat_clean() {
    if common::skip_without_tool("cargo") {
        return;
    }
    let weave = Weave::new("/Cargo.lock\n/.rwv-owned-digests\n");
    assert!(
        common::git_in(&weave.project(), &["ls-files", "Cargo.lock"]).is_empty(),
        "fixture: this arm ignores the lock, so only the carry brings it"
    );
    let (status, report) = weave.create();
    assert_eq!(
        status, "",
        "the hooks create ran must leave the seat's project repo clean:\n{report}"
    );
}

/// The control: a committed lock carrying an entry no member needs, attested
/// as it stands, is pruned by the hook in the seat, and the status read that
/// came back empty above reports it.
#[test]
fn create_over_a_committed_lock_its_manifests_do_not_need_rewrites_it() {
    if common::skip_without_tool("cargo") {
        return;
    }
    let weave = Weave::new("");
    let lock = weave.project().join("Cargo.lock");
    let mut bytes = std::fs::read(&lock).unwrap();
    bytes.extend_from_slice(UNUSED_ENTRY.as_bytes());
    std::fs::write(&lock, &bytes).unwrap();
    repoweave::owned_state::stamp_owned_digest(&weave.project(), "Cargo.lock", &bytes).unwrap();
    weave.commit("a lock with an entry no member needs");

    let (status, report) = weave.create();
    assert!(
        status.lines().any(|l| l.ends_with("Cargo.lock")),
        "the hook prunes the entry and the seat shows it; status was:\n{status}\n{report}"
    );
}
