const MANAGED_REPO: &str = "github/org/docs-tool";
const PROJECT: &str = "app";

struct Workspace {
    root: PathBuf,
    managed_repo: PathBuf,
}

fn init_repo(path: &Path) -> String {
    std::fs::create_dir_all(path).unwrap();
    git(&["init", "-b", "main"], path);
    git(&["config", "user.email", "test@test.com"], path);
    git(&["config", "user.name", "Test"], path);
    write(path, "README.md", "init\n");
    git(&["add", "."], path);
    git(&["commit", "-m", "initial"], path);
    git_out(&["rev-parse", "HEAD"], path)
}

/// The primary workspace, whose one managed repo generates reference pages
/// from templates the way repoweave does.
///
/// `declare` chooses whether that repo commits repoweave's real
/// `.gitattributes`. It is the only difference between
/// [`a_land_conflict_in_a_generated_artifact_resolves_mechanically`] and
/// [`the_same_land_conflict_without_the_declaration_stops_the_sync`]: same
/// paths, same commits, same operation.
fn make_primary(tmp: &Path, declare: bool) -> Workspace {
    let ws = tmp.join("ws");
    let managed_repo = ws.join(MANAGED_REPO);
    init_repo(&managed_repo);

    if declare {
        write(&managed_repo, ".gitattributes", &declared_paths());
    }
    write(
        &managed_repo,
        &format!("{TEMPLATES}/land.md.tmpl"),
        "land\n",
    );
    regenerate(&managed_repo);
    git(&["add", "."], &managed_repo);
    git(
        &["commit", "-m", "docs: generate the reference index"],
        &managed_repo,
    );
    let managed_sha = git_out(&["rev-parse", "HEAD"], &managed_repo);

    let project_dir = ws.join("projects").join(PROJECT);
    init_repo(&project_dir);
    // The lock's own replay exclusion, which `--strategy rebase` requires.
    write(&project_dir, ".gitattributes", "rwv.lock merge=rwv-ours\n");
    write(
        &project_dir,
        "rwv.toml",
        &format!(
            "[repositories.\"{MANAGED_REPO}\"]\ntype = \"git\"\nurl = \"file://{repo}\"\nversion = \"main\"\nrole = \"owned\"\n",
            repo = common::url_path(&managed_repo)
        ),
    );
    write(
        &project_dir,
        "rwv.lock",
        &format!(
            "[repositories.\"{MANAGED_REPO}\"]\ntype = \"git\"\nurl = \"file://{repo}\"\nversion = \"{managed_sha}\"\n",
            repo = common::url_path(&managed_repo)
        ),
    );
    git(
        &["add", ".gitattributes", "rwv.toml", "rwv.lock"],
        &project_dir,
    );
    git(&["commit", "-m", "lock: initial"], &project_dir);

    write(&ws, ".rwv-active", &format!("{PROJECT}\n"));

    Workspace {
        root: ws,
        managed_repo,
    }
}

fn create_workweave(primary: &Workspace, weaveroot: &Path, name: &str) -> Workspace {
    rwv()
        .args(["workweave", PROJECT, "create", name])
        .current_dir(&primary.root)
        .assert()
        .success();

    let root = weaveroot.join(format!("{PROJECT}--{name}"));
    Workspace {
        managed_repo: root.join(MANAGED_REPO),
        root,
    }
}

/// Fixture precondition: no durable definition of the driver is reachable from
/// this repo's config.
///
/// Load-bearing, not decoration. `plant_rwv_merge_driver_config` writes such a
/// definition into project repos, and where one exists a declared path
/// resolves whatever any call site states — so every assertion below about the
/// *policy* would hold for a call site that stated nothing at all. A managed
/// repo never receives the plant; this is the assertion that keeps that true.
fn assert_no_durable_definition(repo: &Path) {
    assert!(
        !has_rwv_merge_driver_config(repo).unwrap(),
        "fixture precondition: `merge.rwv-ours.driver` must be undefined in {} — \
         with a durable definition present the declared path resolves however \
         the replay is invoked, and this fixture could not tell a stated policy \
         from an ignored one (is it set in your global git config?)",
        repo.display()
    );
}

/// `<side>` regenerates the reference index after adding a verb, and locks.
/// The template additions are disjoint new files, so the *sources* merge
/// cleanly; the two regenerated indexes are what collide.
fn add_a_verb_and_lock(ws: &Workspace, verb: &str) {
    write(
        &ws.managed_repo,
        &format!("{TEMPLATES}/{verb}.md.tmpl"),
        &format!("{verb}\n"),
    );
    regenerate(&ws.managed_repo);
    git(&["add", "."], &ws.managed_repo);
    git(
        &["commit", "-m", &format!("docs: document `{verb}`")],
        &ws.managed_repo,
    );
    rwv()
        .args(["lock", "--commit"])
        .current_dir(&ws.root)
        .assert()
        .success();
}

