fn git(args: &[&str], dir: &Path) {
    let out = common::git()
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "Test")
        .env("GIT_AUTHOR_EMAIL", "test@test.com")
        .env("GIT_COMMITTER_NAME", "Test")
        .env("GIT_COMMITTER_EMAIL", "test@test.com")
        .output()
        .expect("git command failed to start");
    assert!(
        out.status.success(),
        "git {:?} in {} failed:\n{}",
        args,
        dir.display(),
        String::from_utf8_lossy(&out.stderr)
    );
}

fn git_out(args: &[&str], dir: &Path) -> String {
    let out = common::git()
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "Test")
        .env("GIT_AUTHOR_EMAIL", "test@test.com")
        .env("GIT_COMMITTER_NAME", "Test")
        .env("GIT_COMMITTER_EMAIL", "test@test.com")
        .output()
        .expect("git command failed to start");
    assert!(
        out.status.success(),
        "git {:?} in {} failed:\n{}",
        args,
        dir.display(),
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8(out.stdout).unwrap().trim().to_string()
}

fn rwv() -> AssertCommand {
    common::rwv()
}

fn write(repo: &Path, rel: &str, contents: &str) {
    let path = repo.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, contents).unwrap();
}

fn read(repo: &Path, rel: &str) -> String {
    common::read_normalized(repo.join(rel))
}

// ---------------------------------------------------------------------------
// The generator, and the gate that blocks on its output
// ---------------------------------------------------------------------------

/// The fixture's generator: [`ARTIFACT`] is the sorted list of the verbs that
/// have a template. It reads the source directory rather than being handed its
/// answer, so "stale" here means what it means in repoweave — the committed
/// artifact does not match what the sources now imply.
fn regenerate(repo: &Path) {
    let mut verbs: Vec<String> = std::fs::read_dir(repo.join(TEMPLATES))
        .expect("the source of record must exist")
        .map(|e| {
            e.unwrap()
                .file_name()
                .to_string_lossy()
                .trim_end_matches(".md.tmpl")
                .to_owned()
        })
        .collect();
    verbs.sort();
    let body: String = verbs.iter().map(|v| format!("- {v}\n")).collect();
    write(repo, ARTIFACT, &format!("# Verbs\n\n{body}"));
}

/// `scripts/ci-local.sh`'s final stage, in miniature: regenerate, then diff the
/// working tree against the index. Blocking, and the only thing that makes a
/// mechanical side-pick safe — the pick is allowed to be wrong because this
/// refuses to let a wrong one ship.
fn drift_gate(repo: &Path) -> Result<(), String> {
    regenerate(repo);
    let out = common::git()
        .args(["diff", "--exit-code", "--", "docs/reference/"])
        .current_dir(repo)
        .output()
        .expect("git diff failed to start");
    if out.status.success() {
        Ok(())
    } else {
        Err(String::from_utf8_lossy(&out.stdout).into_owned())
    }
}

