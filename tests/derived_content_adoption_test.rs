//! Repoweave's own adoption of the derived-content merge policy, exercised as
//! a land.
//!
//! Repoweave commits `.gitattributes` lines
//! declaring `docs/reference/{explain,schemas,prime}` derived, and a land
//! conflict in one of those paths then resolves mechanically — after which the
//! repo's own drift gate is what forces the regeneration commit. Until this,
//! the rule was prose repeated in every piece of standing guidance: "on a land
//! conflict take either side, re-run the generator, commit the regen."
//!
//! ## Why the fixture is shaped the way it is
//!
//! The definition half of the primitive can reach a replay by two routes: the
//! `DerivedContentPolicy` the call site states, and the durable
//! `merge.rwv-ours.driver` config `plant_rwv_merge_driver_config` writes.
//! `verify_replay_exclusion_invariant` plants that config in the **project**
//! repo before every rebase-strategy phase, so a fixture that watched a
//! declared path resolve *there* would pass whether or not anything stated a
//! policy.
//!
//! So the subject here is a **manifest** repo, which never receives the plant
//! — and [`assert_no_durable_definition`] says so out loud before every sync,
//! because that absence is what leaves the stated policy as the only route.
//! That is also the honest model of repoweave itself: repoweave is a managed
//! repo inside a weave, not the project repo of one, so its declarations are
//! honored through `apply_strategy`'s replays and nothing else.
//!
//! The declaration under test is repoweave's real one. [`declared_paths`]
//! reads the committed `.gitattributes` from the source tree and the fixture
//! commits those exact bytes, so the globs git evaluates here are the globs
//! git evaluates in the repo — including the `templates/` carve-out, which
//! [`the_templates_the_generator_reads_stay_authored`] holds to its claim.

use assert_cmd::Command as AssertCommand;
use repoweave::git::{git_vcs, has_rwv_merge_driver_config};
use repoweave::vcs::ConflictOp;
use std::path::{Path, PathBuf};

mod common;

// ---------------------------------------------------------------------------
// The paths repoweave declares derived
// ---------------------------------------------------------------------------

/// Repoweave's committed `.gitattributes` — the adoption itself.
fn declared_paths() -> String {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(".gitattributes");
    std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "repoweave must declare its derived paths in {}: {e}",
            path.display()
        )
    })
}

/// A generated page under `docs/reference/explain/`, and the fixture's stand-in
/// for every artifact `generate-explain` writes.
const ARTIFACT: &str = "docs/reference/explain/index.md";

/// The source of record `ARTIFACT` is derived from. Authored, and deliberately
/// outside the declaration.
const TEMPLATES: &str = "docs/reference/explain/templates";

#[test]
fn repoweave_declares_its_generated_reference_artifacts_derived() {
    let attrs = declared_paths();
    for dir in [
        "docs/reference/explain",
        "docs/reference/schemas",
        "docs/reference/prime",
    ] {
        let needle = format!("{dir}/**");
        assert!(
            attrs.lines().any(|l| {
                let l = l.trim();
                !l.starts_with('#') && l.starts_with(&needle) && l.ends_with("merge=rwv-ours")
            }),
            "`{dir}` is regenerated by `cargo run --bin generate-explain` and \
             the drift gate blocks on it, so a land conflict there has no \
             answer worth adjudicating — it must be declared `merge=rwv-ours`. \
             Got:\n{attrs}"
        );
    }
}

